#[cfg(test)]
mod tests {
    use super::is_text_function;

    #[test]
    fn recognizes_names_case_insensitively() {
        assert!(is_text_function("CRC32"));
        assert!(is_text_function("crc32"));
        assert!(is_text_function("lengthutf8"));
        assert!(!is_text_function("DateTime"));
        assert!(!is_text_function("not_a_scalar_function"));
    }
}
