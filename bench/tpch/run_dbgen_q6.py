#!/usr/bin/env python3
"""Convert, load, validate, and benchmark dbgen LINEITEM in one command.

This is an end-to-end fixed-point Q6 compatibility run, not a TPC-H score.
"""
import argparse
import json
from pathlib import Path

from convert_dbgen import convert_directory
from load_dbgen import load_tables
from q6_dbgen import run_q6


def run_pipeline(binary, database, input_dir, converted_dir, runs=5, warmups=1,
                 timeout=120, converter=convert_directory, loader=load_tables,
                 runner=run_q6):
    binary = Path(binary)
    database = Path(database)
    input_dir = Path(input_dir)
    converted_dir = Path(converted_dir)
    if database.exists():
        raise ValueError("database path must not exist; each run requires a fresh database")
    if not (input_dir / "lineitem.tbl").is_file():
        raise ValueError("input must contain lineitem.tbl generated by dbgen")
    if runs < 1 or warmups < 0 or timeout <= 0:
        raise ValueError("invalid runs, warmups, or timeout")
    if database.resolve() == converted_dir.resolve():
        raise ValueError("database and converted output directories must differ")
    counts = converter(input_dir, converted_dir, selected=["lineitem"])
    if counts["lineitem"] < 1:
        raise ValueError("lineitem.tbl contains no records")
    loaded = loader(binary, database, converted_dir, selected=["lineitem"], timeout=timeout)
    if loaded["tables"][0]["rows"] != counts["lineitem"]:
        raise ValueError("row count differs between converted and imported datasets")
    benchmark = runner(binary, database, converted_dir / "lineitem.tsv",
                       runs=runs, warmups=warmups, timeout=timeout)
    return {
        "workload": "tpch-dbgen-q6-fixed-point-pipeline",
        "official_tpch_score": False,
        "source": "external dbgen lineitem.tbl",
        "rows": counts["lineitem"],
        "load": loaded,
        "query": benchmark,
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, required=True)
    parser.add_argument("--database", type=Path, required=True)
    parser.add_argument("--input-dir", type=Path, required=True)
    parser.add_argument("--converted-dir", type=Path, required=True)
    parser.add_argument("--runs", type=int, default=5)
    parser.add_argument("--warmups", type=int, default=1)
    parser.add_argument("--timeout", type=float, default=120)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args(argv)
    try:
        report = run_pipeline(args.binary, args.database, args.input_dir, args.converted_dir,
                              args.runs, args.warmups, args.timeout)
    except (OSError, RuntimeError, ValueError, KeyError) as error:
        parser.exit(1, f"TPC-H pipeline failed: {error}\n")
    rendered = json.dumps(report, indent=2) + "\n"
    if args.output:
        args.output.write_text(rendered, encoding="utf-8")
    print(rendered, end="")
    return int(report["query"]["coverage"]["verified_queries"] != 1)


if __name__ == "__main__":
    raise SystemExit(main())
