//! Copy-only reconciliation plan for trusted immutable object inventories.
mod key_validation;
use self::key_validation::*;
use std::collections::HashMap;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ObjectMetadata {
    pub key: String,
    pub bytes: u64,
    pub crc32c: u32,
}

impl ObjectMetadata {
    fn same_contents(&self, other: &Self) -> bool {
        self.bytes == other.bytes && self.crc32c == other.crc32c
    }
}

fn index(objects: &[ObjectMetadata]) -> Result<HashMap<&str, &ObjectMetadata>, &'static str> {
    if objects.len() > 65_536 {
        return Err("replica inventory too large");
    }
    let mut indexed = HashMap::with_capacity(objects.len());
    for object in objects {
        if !valid_key(&object.key) || indexed.insert(object.key.as_str(), object).is_some() {
            return Err("unsafe or duplicate replica object key");
        }
    }
    Ok(indexed)
}

fn reject_immutable_conflicts(
    source: &HashMap<&str, &ObjectMetadata>,
    destination: &HashMap<&str, &ObjectMetadata>,
) -> Result<(), &'static str> {
    if source.iter().any(|(key, object)| {
        destination
            .get(*key)
            .is_some_and(|existing| !object.same_contents(existing))
    }) {
        return Err("replica copy conflicts with an existing immutable object");
    }
    Ok(())
}

fn needs_copy(meta: &ObjectMetadata, destination: &HashMap<&str, &ObjectMetadata>) -> bool {
    destination
        .get(meta.key.as_str())
        .is_none_or(|existing| !meta.same_contents(existing))
}

// Small immutable inventories are frequent when copying a fresh generation.
// Validate borrowed keys directly instead of building two hash maps.
fn validate_tiny_inventory(objects: &[ObjectMetadata]) -> Result<(), &'static str> {
    for (index, object) in objects.iter().enumerate() {
        if !valid_key(&object.key) || objects[..index].iter().any(|prior| prior.key == object.key) {
            return Err("unsafe or duplicate replica object key");
        }
    }
    Ok(())
}

/// Return missing or differing source objects in lexicographic key order.
/// Deletions require a separate retention decision and are never planned here.
pub fn plan_replica_copies(
    source: &[ObjectMetadata],
    destination: &[ObjectMetadata],
) -> Result<Vec<ObjectMetadata>, &'static str> {
    reject_portable_key_aliases(source, destination)?;
    if source.len() <= 8 && destination.len() <= 8 {
        validate_tiny_inventory(source)?;
        validate_tiny_inventory(destination)?;
        let mut missing = Vec::new();
        for object in source {
            match destination
                .iter()
                .find(|candidate| candidate.key == object.key)
            {
                Some(existing) if !object.same_contents(existing) => {
                    return Err("replica copy conflicts with an existing immutable object");
                }
                None => missing.push(object.clone()),
                Some(_) => {}
            }
        }
        missing.sort_unstable_by(|left, right| left.key.cmp(&right.key));
        return Ok(missing);
    }
    // Inventories generated by inventory_snapshot are already sorted by
    // object key. Reconcile them with a two-cursor merge, without allocating
    // two maps or sorting the missing set. Retain the strict indexed fallback
    // for arbitrary unordered caller inventories.
    if source.len() > 65_536 || destination.len() > 65_536 {
        return Err("replica inventory too large");
    }
    let sorted = |items: &[ObjectMetadata]| items.windows(2).all(|pair| pair[0].key < pair[1].key);
    if sorted(source) && sorted(destination) {
        if source
            .iter()
            .chain(destination)
            .any(|item| !valid_key(&item.key))
        {
            return Err("unsafe or duplicate replica object key");
        }
        let mut missing = Vec::new();
        let mut dst = 0usize;
        for object in source {
            while dst < destination.len() && destination[dst].key < object.key {
                dst += 1;
            }
            if let Some(existing) = destination.get(dst).filter(|item| item.key == object.key) {
                if !object.same_contents(existing) {
                    return Err("replica copy conflicts with an existing immutable object");
                }
            } else {
                missing.push(object.clone());
            }
        }
        return Ok(missing);
    }
    let source = index(source)?;
    let destination = index(destination)?;
    // A generation-scoped key is immutable: returning it for a conflicting
    // copy would ask the transport to overwrite an existing object.
    reject_immutable_conflicts(&source, &destination)?;
    // Sort borrowed metadata first. Only clone final output in sorted order.
    let mut changed: Vec<&ObjectMetadata> = source
        .into_values()
        .filter(|meta| needs_copy(meta, &destination))
        .collect();
    changed.sort_unstable_by(|left, right| left.key.cmp(&right.key));
    Ok(changed.into_iter().cloned().collect())
}

/// Both sides of a validated, immutable replica inventory difference.
///
/// `destination_only` is diagnostic data, not a deletion plan. Retention
/// and snapshot lineage must be checked separately before removing objects.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ReplicaInventoryDelta {
    pub copies: Vec<ObjectMetadata>,
    pub destination_only: Vec<ObjectMetadata>,
}

fn sorted_refs(objects: &[ObjectMetadata]) -> Result<Vec<&ObjectMetadata>, &'static str> {
    let mut ordered = objects.iter().collect::<Vec<_>>();
    if !ordered.windows(2).all(|pair| pair[0].key < pair[1].key) {
        ordered.sort_unstable_by(|a, b| a.key.cmp(&b.key));
    }
    if ordered.iter().any(|object| !valid_key(&object.key))
        || ordered.windows(2).any(|pair| pair[0].key == pair[1].key)
    {
        return Err("unsafe or duplicate replica object key");
    }
    Ok(ordered)
}

/// Reconcile both directions in a single sorted merge.
///
/// Validate all keys and reject conflicting immutable content before
/// returning either result. Borrowed metadata is sorted only for unordered
/// inventories, and payloads are cloned only for differences.
pub fn reconcile_replica_inventories(
    source: &[ObjectMetadata],
    destination: &[ObjectMetadata],
) -> Result<ReplicaInventoryDelta, &'static str> {
    if source.len() > 65_536 || destination.len() > 65_536 {
        return Err("replica inventory too large");
    }
    let src = sorted_refs(source)?;
    let dst = sorted_refs(destination)?;
    let (mut left, mut right) = (0usize, 0usize);
    let mut result = ReplicaInventoryDelta {
        copies: Vec::new(),
        destination_only: Vec::new(),
    };
    while left < src.len() || right < dst.len() {
        match (src.get(left), dst.get(right)) {
            (Some(a), Some(b)) => match a.key.cmp(&b.key) {
                std::cmp::Ordering::Less => {
                    result.copies.push((**a).clone());
                    left += 1;
                }
                std::cmp::Ordering::Greater => {
                    result.destination_only.push((**b).clone());
                    right += 1;
                }
                std::cmp::Ordering::Equal => {
                    if !a.same_contents(b) {
                        return Err("replica copy conflicts with an existing immutable object");
                    }
                    left += 1;
                    right += 1;
                }
            },
            (Some(a), None) => {
                result.copies.push((**a).clone());
                left += 1;
            }
            (None, Some(b)) => {
                result.destination_only.push((**b).clone());
                right += 1;
            }
            (None, None) => break,
        }
    }
    Ok(result)
}

