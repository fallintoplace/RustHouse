#[cfg(test)]
mod sorted_borrowed_planner_tests {
    use super::*;

    #[test]
    fn sorted_inventories_match_unordered_reference_across_pages() {
        let source = (0..2048)
            .map(|index| ObjectMetadata {
                key: format!("part_{index:05}/data.bin"),
                bytes: 1 + (index % 19) as u64,
                crc32c: index,
            })
            .collect::<Vec<_>>();
        let destination = source.iter().step_by(3).cloned().collect::<Vec<_>>();
        let sorted = ReplicaCopyPlanner::new(&source, &destination).unwrap();
        let mut reversed_source = source.clone();
        let mut reversed_destination = destination.clone();
        reversed_source.reverse();
        reversed_destination.reverse();
        let unordered = ReplicaCopyPlanner::new(&reversed_source, &reversed_destination).unwrap();
        assert_eq!(sorted.len(), unordered.len());
        for cursor in [
            None,
            Some("part_00400/data.bin"),
            Some("part_02047/data.bin"),
        ] {
            for limit in [0, 1, 2, 9, 5000] {
                assert_eq!(
                    sorted.batch_after(cursor, 500, limit).unwrap(),
                    unordered.batch_after(cursor, 500, limit).unwrap()
                );
            }
        }
    }

    #[test]
    fn sorted_planner_rejects_conflicts_and_invalid_keys() {
        let a = ObjectMetadata {
            key: "part_1/data.bin".into(),
            bytes: 1,
            crc32c: 1,
        };
        let b = ObjectMetadata {
            crc32c: 2,
            ..a.clone()
        };
        assert!(ReplicaCopyPlanner::new(std::slice::from_ref(&a), &[b]).is_err());
        assert!(ReplicaCopyPlanner::new(&[a.clone(), a.clone()], &[]).is_err());
        let invalid = ObjectMetadata {
            key: "../oops".into(),
            ..a
        };
        assert!(ReplicaCopyPlanner::new(&[invalid], &[]).is_err());
    }
}

#[cfg(test)]
mod lossless_replica_copy_page_tests {
    use super::*;

    fn object(name: &str, bytes: u64) -> ObjectMetadata {
        ObjectMetadata {
            key: name.into(),
            bytes,
            crc32c: bytes as u32,
        }
    }

    #[test]
    fn partial_byte_budgets_never_lose_skipped_keys() {
        let sources = [
            object("a/data.bin", 8),
            object("b/data.bin", 6),
            object("c/data.bin", 2),
            object("d/data.bin", 0),
        ];
        let mut cursor: Option<String> = None;
        let mut copied = Vec::new();
        for _ in 0..sources.len() + 1 {
            let page = plan_replica_copy_page(&sources, &[], cursor.as_deref(), 10, 2).unwrap();
            copied.extend(page.copies.iter().map(|item| item.key.clone()));
            cursor = page.next_after;
            if cursor.is_none() {
                break;
            }
        }
        assert_eq!(
            copied,
            ["a/data.bin", "b/data.bin", "c/data.bin", "d/data.bin"]
        );
    }

    #[test]
    fn blocked_first_object_fails_instead_of_returning_unsafe_cursor() {
        let source = [object("a/file", 11), object("b/file", 1)];
        assert!(plan_replica_copy_page(&source, &[], None, 10, 8).is_err());
        let page = plan_replica_copy_page(&source, &[], Some("a/file"), 10, 8).unwrap();
        assert_eq!(page.copies, vec![source[1].clone()]);
        assert!(page.next_after.is_none());
    }

    #[test]
    fn pagination_respects_one_item_limits_and_immutable_conflicts() {
        let source = [object("a/file", 0), object("b/file", 0)];
        let first = plan_replica_copy_page(&source, &[], None, 0, 1).unwrap();
        assert_eq!(first.copies, vec![source[0].clone()]);
        assert_eq!(first.next_after.as_deref(), Some("a/file"));
        let second =
            plan_replica_copy_page(&source, &[], first.next_after.as_deref(), 0, 1).unwrap();
        assert_eq!(second.copies, vec![source[1].clone()]);
        assert!(second.next_after.is_none());
        assert!(plan_replica_copy_page(&source, &[], None, 0, 0).is_err());
        let conflict = [object("a/file", 999)];
        assert!(plan_replica_copy_page(&source, &conflict, None, 100, 10).is_err());
    }
}
